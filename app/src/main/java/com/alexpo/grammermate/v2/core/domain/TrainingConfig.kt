package com.alexpo.grammermate.v2.core.domain

/**
 * Конфигурация параметров тренировки — единый источник констант для логики
 * формирования пулов, подуроков, боссов и порогов освоения.
 *
 * Чистый Kotlin (object), без Android-зависимостей. Значения перенесены из
 * legacy `TrainingConfig.kt` (v1) без изменения бизнес-смысла; здесь они
 * собраны в одном месте и доступны всем слоям через домен.
 *
 * Константы сгруппированы по смыслу:
 *  - размеры подурока/сессии и множители (ELITE);
 *  - пороги боссов и освоения урока/словаря;
 *  - пороги наград босса (бронза/серебро/золото).
 */
object TrainingConfig {

    // ---------------------------------------------------------------------------------------
    //  Подурок (sub-lesson) — размер
    // ---------------------------------------------------------------------------------------

    /** Размер подурока по умолчанию, карточек. */
    const val SUB_LESSON_SIZE_DEFAULT = 10

    /** Минимальный размер подурока, карточек. */
    const val SUB_LESSON_SIZE_MIN = 6

    /** Максимальный размер подурока, карточек. */
    const val SUB_LESSON_SIZE_MAX = 12

    // ---------------------------------------------------------------------------------------
    //  ELITE / боссы
    // ---------------------------------------------------------------------------------------

    /** Количество шагов в ELITE-сессии. */
    const val ELITE_STEP_COUNT = 7

    /**
     * Сколько подуроков нужно завершить, чтобы открыть (unlock) босса урока.
     */
    const val BOSS_UNLOCK_SUB_LESSONS = 15

    /**
     * Множитель размера ELITE-сессии относительно обычной (увеличивает пул).
     */
    const val ELITE_SIZE_MULTIPLIER = 1.25

    /** Максимальное число карточек в одном BOSS-пуле. */
    const val MAX_BOSS_CARDS = 300

    /** Порог правильных ответов (%), Bronze-награда за босса. */
    const val BOSS_BRONZE_PCT = 30.0

    /** Порог правильных ответов (%), Silver-награда за босса. */
    const val BOSS_SILVER_PCT = 60.0

    /** Порог правильных ответов (%), Gold-награда за босса. */
    const val BOSS_GOLD_PCT = 90.0

    // ---------------------------------------------------------------------------------------
    //  Пороги освоения / подсказки / повторения
    // ---------------------------------------------------------------------------------------

    /**
     * Порог завершения урока по числу показанных карточек.
     * Равен размеру основного пула [MAIN_POOL_SIZE] и порогу мастерства
     * [MASTERY_THRESHOLD].
     */
    const val LESSON_COMPLETION_CARD_THRESHOLD = 150

    /**
     * Сколько подсказок подряд может получить пользователь, прежде чем карточка
     * считается «проваленной» по подсказкам.
     */
    const val HINT_THRESHOLD = 3

    /** Лимит карточек в режиме обзора/повторения (review). */
    const val REVIEW_LIMIT = 300

    /**
     * Сколько раз карточка/урок должны быть отвечены верно, чтобы считаться
     * «выученными» (порог learned). Дублирует [SrsConstants.LEARNED_THRESHOLD]
     * — здесь повторён для удобства тренировочной логики, не зависящей от SRS.
     *
     * @see com.alexpo.grammermate.v2.core.domain.srs.SrsConstants.LEARNED_THRESHOLD
     */
    const val LEARNED_THRESHOLD = 3

    // ---------------------------------------------------------------------------------------
    //  Пул / мастерство
    // ---------------------------------------------------------------------------------------

    /**
     * Порог мастерства: количество показанных карточек урока, после которого
     * урок считается освоенным. Совпадает с [LESSON_COMPLETION_CARD_THRESHOLD].
     */
    const val MASTERY_THRESHOLD = 150

    /** Размер основного (main) пула карточек для тренировки/повторения. */
    const val MAIN_POOL_SIZE = 150
}
